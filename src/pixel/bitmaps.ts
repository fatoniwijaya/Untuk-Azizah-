// Pixel matrices for OLED monochrome display (logical canvas: 256 x 160)
// 0 = transparent, 1 = white pixel, 2 = black interior pixel (gives solid silhouette over skyline)

export type PixelMatrix = number[][];

export const parseBitmap = (lines: string[]): PixelMatrix => {
  return lines.map((line) =>
    line.split('').map((char) => {
      if (char === '#' || char === '1') return 1;
      if (char === '.' || char === '0' || char === ' ') return 0;
      if (char === 'x' || char === '2') return 2; // Black interior pixel
      return 0;
    })
  );
};

